/**
 * tokens/famous-schemes.ts — 20 of the world's most-loved editor color schemes
 * (+ the operator's own "Pelly" scheme imported from a JetBrains .icls), authored
 * as `ColorScheme`s over the §2 SemanticColors so they drive BOTH the app chrome
 * and the generated Monaco/xterm themes (one palette, never desynced).
 *
 * These EXTEND the 20 first-party builtins in tokens.ts (concatenated into
 * BUILTIN_SCHEMES) so they appear in the Settings ▸ Appearance picker and resolve
 * through getScheme()/ThemeProvider like any other scheme. Type-only import of the
 * shared shapes (no runtime cycle with tokens.ts).
 */
import type { ColorScheme, SchemeBase, SemanticColors } from "../tokens.js";

/** A compact palette → a full SemanticColors map (the 18 §2 roles). */
interface Palette {
  bg: string;
  surface: string;
  surface2: string;
  inset: string;
  borderSubtle: string;
  borderStrong: string;
  text: string;
  textDim: string;
  brand: string;
  accent: string;
  ok: string;
  warn: string;
  danger: string;
  info: string;
  selection: string;
}

function mk(id: string, name: string, base: SchemeBase, p: Palette): ColorScheme {
  const tokens: SemanticColors = {
    "bg-app": p.bg,
    "bg-surface": p.surface,
    "bg-surface-2": p.surface2,
    "bg-inset": p.inset,
    "border-subtle": p.borderSubtle,
    "border-strong": p.borderStrong,
    "text-primary": p.text,
    "text-secondary": p.textDim,
    "text-disabled": p.textDim,
    brand: p.brand,
    "brand-fg": p.bg,
    accent: p.accent,
    "focus-ring": p.accent,
    ok: p.ok,
    warn: p.warn,
    danger: p.danger,
    info: p.info,
    selection: p.selection,
  };
  return { id, name, base, builtin: true, tokens, filled: true };
}

