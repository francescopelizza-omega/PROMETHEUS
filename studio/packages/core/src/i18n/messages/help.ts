/**
 * i18n/messages/help.ts — the help menu, in eight languages.
 *
 * ── WHY ALL EIGHT LIVE IN ONE FILE ──────────────────────────────────────────────────────────
 *
 * The opposite of `messages/<locale>.ts`, and deliberately so. Those are ~80 paragraphs each,
 * where a file per language is the only readable arrangement. These are one-line labels — often
 * one or two words — and the thing a reviewer needs is to see the eight side by side and spot
 * the odd one out. A `groups` block with all eight versions of "Session" on consecutive lines
 * is reviewable; the same content spread over eight files is not.
 *
 * ── WHAT IS NOT TRANSLATED, EVER ────────────────────────────────────────────────────────────
 *
 * Command NAMES. `/setup` stays `/setup` in Polish, and the engine verbs (`scan`, `install`,
 * `list`) stay English too. An identifier that changes per language cannot be taught, searched
 * for, or pasted from a forum — and a translated verb is simply a verb the engine rejects.
 * Where a description mentions another command, the `/name` inside it survives verbatim;
 * `help.test.ts` asserts exactly that, in every locale, for every string here.
 *
 * ── PARTIAL IS FINE ─────────────────────────────────────────────────────────────────────────
 *
 * `commandHelp()` falls back to the registry's own `summary:` — the single English source — so
 * a command absent here renders in English and nothing breaks. `helpCoverage()` reports the
 * percentage, and `/language` shows it, so "how finished is Dutch?" has a number rather than an
 * opinion. Adding a command to the registry lowers the figure immediately; that is intended.
 */

